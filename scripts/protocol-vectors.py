def b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def invite_body(token: bytes, url: str, vault: str, version: int = INVITE_VERSION) -> bytes:
    u, v = url.encode("utf-8"), vault.encode("utf-8")
    return bytes([version]) + token + bytes([len(u)]) + u + bytes([len(v)]) + v


def with_crc(body: bytes) -> bytes:
    return body + (zlib.crc32(body) & 0xFFFFFFFF).to_bytes(4, "big")


def invite(token: bytes, url: str, vault: str) -> str:
    return INVITE_PREFIX + b64(with_crc(invite_body(token, url, vault)))


ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"


def dangling(s: str) -> str:
    """A base64url string one character longer than a whole number of bytes."""
    extra = {0: 1, 3: 2, 2: 3}[len(s) % 4]
    out = s + "A" * extra
    assert len(out) % 4 == 1
    return out


def unused_bits_body(token: bytes, url: str) -> bytes:
    """An invite body whose encoding ends in unused bits (length % 3 != 0)."""
    for n in range(1, 8):
        body = invite_body(token, url, "v" * n)
        if len(with_crc(body)) % 3 != 0:
            return body
    raise AssertionError("no vault length gives a partial final group")


def dirty_tail(raw: bytes) -> str:
    """Encodes raw, then sets the lowest unused bit of the final character."""
    s = b64(raw)
    assert len(s) % 4 in (2, 3), "the final group must carry unused bits"
    last = ALPHABET.index(s[-1])
    assert last & 1 == 0
    return s[:-1] + ALPHABET[last | 1]


