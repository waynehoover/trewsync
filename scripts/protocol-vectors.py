def path_reason(raw: bytes) -> str | None:
    """The first rule a path breaks, in the order plan/protocol.md lists them."""
    try:
        text = raw.decode("utf-8", errors="strict")
    except UnicodeDecodeError:
        return "utf8"
    if any(0xD800 <= ord(c) <= 0xDFFF for c in text):
        return "utf8"
    if text == "":
        return "empty"
    if len(raw) > MAX_PATH_BYTES:
        return "toolong"
    if any(len(s.encode("utf-8")) > MAX_SEGMENT_BYTES for s in text.split("/")):
        return "segmenttoolong"
    if any(ord(c) < 0x20 or ord(c) == 0x7F for c in text):
        return "control"
    if unicodedata.normalize("NFC", text) != text:
        return "nfc"
    if "\u00a0" in text or "\u202f" in text:
        return "nbsp"
    if "\\" in text:
        return "backslash"
    if text.startswith("/") or text.endswith("/"):
        return "slash"
    segments = text.split("/")
    if any(s == "" for s in segments):
        return "emptysegment"
    if any(s in (".", "..") for s in segments):
        return "dotsegment"
    if any(s.startswith(".") for s in segments):
        return "dotprefix"
    if STAGING_MARK in text:
        return "staging"
    return None


