def deflate_raw(data: bytes, level: int = 6) -> bytes:
    c = zlib.compressobj(level, zlib.DEFLATED, -15)
    return c.compress(data) + c.flush()


def sha256_ctr(seed: str, length: int) -> bytes:
    out = bytearray()
    counter = 0
    while len(out) < length:
        out += hashlib.sha256(seed.encode("utf-8") + counter.to_bytes(4, "big")).digest()
        counter += 1
    return bytes(out[:length])


def frame_vectors() -> dict:
    text = ("The quick brown fox jumps over the lazy dog. " * 100).encode("ascii")
    good = []
    bad = []

    def good_frame(why: str, frame: bytes, raw: bytes) -> None:
        good.append({"why": why, "frame": frame.hex(), "raw": raw.hex(), "name": hashlib.sha256(raw).hexdigest()})

    good_frame("raw", b"\x00hello\n", b"hello\n")
    good_frame("raw whose first byte is 0", b"\x00\x00abc", b"\x00abc")
    good_frame("raw whose first byte is 1", b"\x00\x01abc", b"\x01abc")
    good_frame("deflate", b"\x01" + deflate_raw(text), text)
    good_frame("deflate at level 9", b"\x01" + deflate_raw(text, 9), text)
    good_frame("deflate followed by bytes after the final block, which are ignored", b"\x01" + deflate_raw(text) + b"junk", text)
    # Longer than the 4 KiB slices a bounded inflater feeds itself, so a decoder
    # that only tolerated junk inside its first slice would be caught.
    good_frame("deflate followed by 5000 bytes after the final block", b"\x01" + deflate_raw(text) + b"\xab" * 5000, text)

    generated = [
        {"why": "raw at exactly chunkMax, incompressible", "marker": 0, "gen": {"kind": "sha256-ctr", "seed": "frames", "length": CHUNK_MAX}, "valid": True},
        {"why": "deflate that inflates to exactly chunkMax", "marker": 1, "gen": {"kind": "zeros", "length": CHUNK_MAX}, "valid": True},
        {"why": "raw one byte over chunkMax", "marker": 0, "gen": {"kind": "sha256-ctr", "seed": "frames", "length": CHUNK_MAX + 1}, "valid": False},
        {"why": "deflate that inflates one byte past chunkMax", "marker": 1, "gen": {"kind": "zeros", "length": CHUNK_MAX + 1}, "valid": False},
    ]
    for g in generated:
        if g["gen"]["kind"] == "sha256-ctr":
            raw = sha256_ctr(g["gen"]["seed"], g["gen"]["length"])
        else:
            raw = bytes(g["gen"]["length"])
        g["name"] = hashlib.sha256(raw).hexdigest()
        if g["marker"] == 1:
            payload = deflate_raw(raw)
            g["payloadLength"] = len(payload)
            g["payloadSha256"] = hashlib.sha256(payload).hexdigest()
        g["gen"]["note"] = "raw bytes; a deflate vector deflates them (any level) and the decoded result is what is checked"

    def bad_frame(why: str, frame: bytes) -> None:
        bad.append({"why": why, "frame": frame.hex()})

    bad_frame("an empty frame, with no marker", b"")
    bad_frame("a marker with no payload: chunks are never empty", b"\x00")
    bad_frame("a deflate marker with no stream", b"\x01")
    bad_frame("an unknown marker", b"\x02hello")
    bad_frame("marker 255", b"\xffhello")
    bad_frame("truncated deflate", b"\x01" + deflate_raw(text)[:-3])
    bad_frame("deflate of nothing: chunks are never empty", b"\x01" + deflate_raw(b""))
    bad_frame("not deflate at all", b"\x01" + b"\xff" * 16)
    return {
        "note": [
            "frame = marker (1 byte) || payload. marker 0: payload is the raw chunk. marker 1: raw DEFLATE (RFC 1951).",
            "A receiver refuses a frame longer than chunkMax + 1 bytes before inflating anything,",
            "refuses a payload that inflates past chunkMax, refuses a chunk of zero bytes,",
            "then hashes the raw bytes and compares them with the name it asked for.",
            "Bytes after the final deflate block are ignored: they cannot change the decoded bytes, which the name checks.",
            "A sender uses marker 1 only when the deflated payload is shorter than the raw bytes.",
            "Deflate output need not match between implementations; decoded bytes and names must.",
        ],
        "chunkMax": CHUNK_MAX,
        "good": good,
        "generated": generated,
        "bad": bad,
    }


