def collision(live: list[dict], op: dict, table: dict[int, str]) -> str:
    """plan/protocol.md "Paths", the collision rule, as a reference."""
    target = op["path"]
    if op["type"] == "move" and fold(op["prev"], table) == fold(target, table):
        return "ok"  # a case-only rename keeps every folded key where it was
    if op["type"] == "create" and any(e["path"] == target for e in live):
        return "ok"  # an update of a live path, not a create
    others = [
        e for e in live if e["path"] != target and not (op["type"] == "move" and e["path"] == op["prev"])
    ]
    key = fold(target, table)
    if any(fold(e["path"], table) == key for e in others):
        return "collision"
    dirs: set[str] = set()
    files: set[str] = set()
    for e in others:
        segs = e["path"].split("/")
        for k in range(1, len(segs)):
            dirs.add("/".join(segs[:k]))
        (dirs if e.get("folder") else files).add(e["path"])
    segs = target.split("/")
    for k in range(1, len(segs)):
        d = "/".join(segs[:k])
        fd = fold(d, table)
        spellings = {x for x in dirs if fold(x, table) == fd}
        if spellings and d not in spellings:
            return "collision"
        if any(fold(f, table) == fd for f in files):
            return "collision"
    same = {x for x in dirs if fold(x, table) == key}
    if same and (not op.get("folder") or target not in same):
        return "collision"
    return "ok"


