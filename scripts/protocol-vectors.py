def fold_table() -> dict[int, str]:
    table = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).casefold()
        if folded != chr(cp):
            table[cp] = folded
    return table


def table_digest(table: dict[int, str]) -> str:
    lines = []
    for cp in sorted(table):
        target = " ".join(f"{ord(c):04X}" for c in table[cp])
        lines.append(f"{cp:04X}:{target}\n")
    return hashlib.sha256("".join(lines).encode("ascii")).hexdigest()


def fold(s: str, table: dict[int, str]) -> str:
    """NFC, then the table code point by code point, then NFC again."""
    nfc = unicodedata.normalize("NFC", s)
    folded = "".join(table.get(ord(c), c) for c in nfc)
    return unicodedata.normalize("NFC", folded)


def go_table(table: dict[int, str], digest: str) -> str:
    out = [
        "// Code generated by scripts/protocol-vectors.py. DO NOT EDIT.",
        "",
        "package paths",
        "",
        f"// FoldTableUnicodeVersion is the Unicode version the fold table was taken from.",
        f'const FoldTableUnicodeVersion = "{UNICODE_VERSION}"',
        "",
        "// FoldTableDigest is the SHA-256 of the table's canonical form, which",
        "// protocol-fixtures.json records too, so a test can prove Go and TypeScript",
        "// hold the same table.",
        f'const FoldTableDigest = "{digest}"',
        "",
        "// foldTable maps each code point that full case folding changes to what it",
        "// folds to: Unicode CaseFolding.txt statuses C and F.",
        "var foldTable = map[rune]string{",
    ]
    for cp in sorted(table):
        target = "".join(f"\\U{ord(c):08X}" if ord(c) > 0xFFFF else f"\\u{ord(c):04X}" for c in table[cp])
        # Five hex digits for every key, so gofmt has no column to realign: the
        # highest code point that folds is U+1E921.
        out.append(f'\t0x{cp:05X}: "{target}",')
    out.append("}")
    out.append("")
    return "\n".join(out)


def ts_table(table: dict[int, str], digest: str) -> str:
    # A flat string rather than a literal per entry: 1,530 entries as object
    # literals cost the plugin bundle three times as much. Each entry is the
    # source code point and its fold in hex, space separated, entries split by
    # commas.
    entries = []
    for cp in sorted(table):
        entries.append(" ".join([f"{cp:X}"] + [f"{ord(c):X}" for c in table[cp]]))
    packed = ",".join(entries)
    lines = [
        "// Code generated by scripts/protocol-vectors.py. DO NOT EDIT.",
        "",
        "/** The Unicode version the fold table was taken from. */",
        f'export const FOLD_TABLE_UNICODE_VERSION = "{UNICODE_VERSION}";',
        "",
        "/**",
        " * The SHA-256 of the table's canonical form, which protocol-fixtures.json",
        " * records too, so a test can prove TypeScript and Go hold the same table.",
        " */",
        f'export const FOLD_TABLE_DIGEST = "{digest}";',
        "",
        "/**",
        " * Each code point full case folding changes, and what it folds to: Unicode",
        " * CaseFolding.txt statuses C and F. Entries are comma separated, each the",
        " * source and its fold as space separated hex code points.",
        " */",
        "export const FOLD_TABLE_PACKED =",
    ]
    # Split the literal so no line is unreasonably long.
    chunk = 96
    parts = [packed[i : i + chunk] for i in range(0, len(packed), chunk)]
    for i, part in enumerate(parts):
        end = ";" if i == len(parts) - 1 else " +"
        lines.append(f'  "{part}"{end}')
    lines.append("")
    return "\n".join(lines)


