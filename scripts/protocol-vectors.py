TEXT_EXTENSIONS = [
    "md", "txt", "canvas", "json", "csv", "yml", "yaml", "base", "xml",
    "html", "css", "js", "ts", "svg", "bib", "tex",
]


def ext(path: str) -> str | None:
    """The extension after the last dot, if that dot is in the final segment."""
    dot = path.rfind(".")
    if dot < 0 or dot < path.rfind("/"):
        return None
    return ascii_lower(path[dot + 1 :])


def ascii_lower(s: str) -> str:
    """Lower case for A to Z only, so no runtime's Unicode rules are involved."""
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in s)


def formats(table: dict[int, str]) -> dict:
    samples = [
        "a.md", "a.MD", "a.Md", "a.txt", "a.TXT", "a.excalidraw.md", "a.Excalidraw.MD",
        "a.canvas", "a.base", "a.json", "a.yaml", "a.png", "a.pdf", "a", "a.md.png",
        "dir.md/x", "dir.md/x.md", "Folder/Deep/Note.md", ".obsidian/x.md", "a.mdx",
    ]

    def syncable(p: str) -> bool:
        return path_reason(p.encode("utf-8")) is None

    def chunking_text(p: str) -> bool:
        e = ext(p)
        return e is not None and e in TEXT_EXTENSIONS

    def readable(p: str) -> bool:
        lower = ascii_lower(p)
        return syncable(p) and (lower.endswith(".md") or lower.endswith(".txt"))

    def editable(p: str) -> bool:
        return readable(p) and not ascii_lower(p).endswith(".excalidraw.md")

    return {
        "note": [
            "Five policies, kept separate even where two agree today (PLAN M0.5 task 3).",
            "syncable: the path rules above. chunkingText: an extension in textExtensions, compared in ASCII lower case;",
            "it only picks chunk sizes, so a wrong answer costs efficiency, never correctness.",
            "searchable and mcpReadable: syncable, and ending .md or .txt in any ASCII case, drawings included.",
            "mcpEditable: mcpReadable and not ending .excalidraw.md in any ASCII case.",
        ],
        "textExtensions": TEXT_EXTENSIONS,
        "samples": [
            {
                "path": p,
                "syncable": syncable(p),
                "chunkingText": chunking_text(p),
                "searchable": readable(p),
                "mcpReadable": readable(p),
                "mcpEditable": editable(p),
            }
            for p in samples
        ],
    }


