"""The reference implementation of the protocol 1 contract, and its vectors.

Run it with the interpreter the table is pinned to:

    uv run --no-project --python 3.13 scripts/protocol-vectors.py

It writes three things and nothing else (or, with --check, writes nothing
and exits 1 naming any of the three that is not what it would write, which is
the gate step that keeps a hand edit or a forgotten regeneration from passing):

  internal/paths/fold_table.go     the case fold table, for Go
  client/src/core/fold-table.ts    the same table, for TypeScript
  protocol-fixtures.json           the sections named in SECTIONS, replaced;
                                   every other key in the file is kept as it is

Why a third language. PLAN.md M0.5 requires each implementation to consume
vectors it did not produce: "generating your own vectors and passing your own
tests proves nothing". This script is neither the server nor the client, and
it is small enough to read against plan/protocol.md line by line. Go and
TypeScript both have to reach its verdicts, and both have to hold a fold table
whose digest equals the one recorded here.

The fold is Unicode full case folding (statuses C and F of CaseFolding.txt),
taken from Python's `str.casefold`, which applies exactly that mapping code
point by code point. The Unicode version is whatever this interpreter carries,
and the script refuses to run under any other, so regenerating it cannot
quietly change which names collide.
"""

